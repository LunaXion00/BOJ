SELECT PRODUCT_ID, PRODUCT_NAME, TOTAL_AMOUNT * PRICE AS TOTAL_SALES
FROM (
    SELECT A.PRODUCT_ID, A.PRODUCT_NAME, SUM(B.AMOUNT) AS TOTAL_AMOUNT, A.PRICE
    FROM FOOD_PRODUCT A INNER JOIN FOOD_ORDER B ON A.PRODUCT_ID = B.PRODUCT_ID
    WHERE TO_CHAR(B.PRODUCE_DATE, 'YYYYMM') = '202205'
    GROUP BY A.PRODUCT_ID, A.PRODUCT_NAME, A.PRICE
        )
ORDER BY TOTAL_SALES DESC, PRODUCT_ID;